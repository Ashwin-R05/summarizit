import 'dart:convert';
import 'package:archive/archive.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:summarizit/services/file_export_service.dart';

void main() {
  group('FileExportService — DOCX Generation', () {
    late FileExportService exportService;

    setUp(() {
      exportService = FileExportService();
    });

    test('Produces a valid ZIP archive containing required Open XML files', () {
      final bullets = [
        'First key point with standard text.',
        'Second key point with special characters like <XML> & "Quotes".',
        'Third key point summarizing findings.',
      ];

      // Generate the binary bytes using FileExportService
      final docxBytes = exportService.generateDocxBytes(bullets);
      expect(docxBytes, isNotEmpty);

      // Decode the generated bytes as a ZIP archive
      final archive = ZipDecoder().decodeBytes(docxBytes);
      expect(archive.files, isNotEmpty);

      // Verify the presence of required Office Open XML structure files
      final fileNames = archive.files.map((file) => file.name).toSet();
      final baseNames = archive.files.map((file) => file.name.split('/').last).toSet();

      // Check for exact paths
      expect(fileNames, contains('[Content_Types].xml'));
      expect(fileNames, contains('word/document.xml'));
      expect(fileNames, contains('word/_rels/document.xml.rels'));
      expect(fileNames, contains('word/numbering.xml'));

      // Check base file names
      expect(baseNames, contains('[Content_Types].xml'));
      expect(baseNames, contains('document.xml'));
      expect(baseNames, contains('document.xml.rels'));
      expect(baseNames, contains('numbering.xml'));

      // Verify content of document.xml contains the escaped bullets
      final docFile = archive.findFile('word/document.xml');
      expect(docFile, isNotNull);
      final docXml = utf8.decode(docFile!.content as List<int>);
      expect(docXml, contains('SummarizIt — Summary'));
      expect(docXml, contains('First key point with standard text.'));
      expect(docXml, contains('Second key point with special characters like &lt;XML&gt; &amp; &quot;Quotes&quot;.'));
    });
  });
}
